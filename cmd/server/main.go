// @title           slipwise API
// @version         1.0
// @description     Backend for slipwise — auth, realtime chat, notifications, and betting modules.
// @host            localhost:8080
// @BasePath        /
// @securityDefinitions.apikey  BearerAuth
// @in                          header
// @name                        Authorization
// @description                 Type "Bearer" followed by a space and the JWT access token.
package main

import (
	"context"
	"errors"
	"log"
	"log/slog"
	"net/http"
	"os"
	"os/signal"
	"syscall"
	"time"

	"slipwise/internal/auth"
	authhandler "slipwise/internal/auth/handler"
	"slipwise/internal/auth/repository"
	authservice "slipwise/internal/auth/service"
	bettinghandler "slipwise/internal/betting/handler"
	"slipwise/internal/betting/provider/sportybet"
	bettingrepo "slipwise/internal/betting/repository"
	bettingservice "slipwise/internal/betting/service"
	"slipwise/internal/config"
	db "slipwise/internal/db/generated"
	"slipwise/internal/httpserver"
	"slipwise/internal/mailer"
	"slipwise/internal/notification"
	"slipwise/internal/worker"

	_ "slipwise/docs" // generated by `swag init`, provides the swagger.json the router serves
)

// shutdownTimeout is how long a graceful shutdown waits for in-flight
// requests to finish before forcing the process to exit anyway.
const shutdownTimeout = 10 * time.Second

func main() {
	// Structured logging: every log line from here on is a JSON
	// object (level, message, and whatever key/value fields a call
	// site adds), not a free-text string. This is what makes
	// production logs queryable/filterable instead of grep-only.
	slog.SetDefault(slog.New(slog.NewJSONHandler(os.Stdout, nil)))

	cfg, err := config.Load()
	if err != nil {
		log.Fatalf("config error: %v", err)
	}

	pool := mustConnectDB(cfg.DatabaseURL)
	defer pool.Close()

	queries := db.New(pool)

	jwtIssuer := auth.NewJWTIssuer(cfg.JWTSecret)
	brevoMailer := mailer.NewBrevoMailer(cfg.BrevoAPIKey, cfg.BrevoSenderEmail)

	authRepo := repository.NewAuthRepository(queries)
	authSvc := authservice.NewAuthService(authRepo, jwtIssuer, brevoMailer, cfg.GoogleClientID, cfg.FeedbackEmail)
	authH := authhandler.NewAuthHandler(authSvc)

	// Betting module
	cfClient := worker.NewCloudflareClient(cfg.CloudflareWorkerURL)
	sportyProvider := sportybet.NewProvider(cfClient)

	bettingRepo := bettingrepo.NewRepository(pool)
	bettingSvc := bettingservice.NewBettingService(
		bettingRepo,
		map[string]bettingservice.TicketProvider{
			"SPORTYBET": sportyProvider,
		},
	)
	bettingH := bettinghandler.NewBettingHandler(bettingSvc)

	// Start daily orphan cleanup job
	cleanupJob := worker.NewCleanupJob(bettingSvc)
	go cleanupJob.Start(context.Background())

	// Initialize FCM
	fcmSvc, err := notification.NewFCMService(context.Background(), cfg.FirebaseCredentialsJSON)
	if err != nil {
		slog.Error("fcm initialization failed (invalid FIREBASE_CREDENTIALS_JSON)", "error", err)
		os.Exit(1)
	}

	// Start live match poller
	poller := worker.NewPoller(cfClient, bettingRepo, worker.NewLiveEvaluator(bettingRepo, fcmSvc), 60*time.Second)
	go poller.Start(context.Background())

	// As each new domain (realtime, notifications, betting...) gets its
	// own repo/service/handler, wire it here and add it to Handlers below.
	// Route mounting itself never happens in this file — see
	// internal/httpserver/router.go.
	handlers := httpserver.Handlers{
		Auth:    authH,
		Betting: bettingH,
		Poller:  poller,
	}

	r := httpserver.NewRouter(handlers, jwtIssuer, cfg.AllowedOrigins, cfg.TrustedProxyCIDRs, cfg.CronSecret)

	srv := &http.Server{
		Addr:    ":" + cfg.Port,
		Handler: r,
	}

	// Run the server in a goroutine so main() stays free to listen for
	// a shutdown signal below. ListenAndServe blocks until the server
	// stops; ErrServerClosed is the expected error on a clean
	// Shutdown() call, not a real failure.
	go func() {
		slog.Info("server starting", "port", cfg.Port)
		if err := srv.ListenAndServe(); err != nil && !errors.Is(err, http.ErrServerClosed) {
			log.Fatalf("server error: %v", err)
		}
	}()

	// Block until the OS asks us to stop — Ctrl+C locally (SIGINT), or
	// SIGTERM from whatever's managing the process in staging/prod
	// (systemd, Docker, a platform's deploy tooling). Without this,
	// the old log.Fatal(ListenAndServe(...)) approach meant every
	// deploy/restart just killed in-flight requests instantly.
	quit := make(chan os.Signal, 1)
	signal.Notify(quit, os.Interrupt, syscall.SIGTERM)
	<-quit

	slog.Info("shutdown signal received, draining in-flight requests")

	ctx, cancel := context.WithTimeout(context.Background(), shutdownTimeout)
	defer cancel()

	if err := srv.Shutdown(ctx); err != nil {
		log.Fatalf("forced shutdown after %s: %v", shutdownTimeout, err)
	}

	slog.Info("server exited cleanly")
}
