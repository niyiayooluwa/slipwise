// @title           Sportloga API
// @version         1.0
// @description     Backend for Sportloga — auth, realtime chat, notifications, and betting modules.
// @host            localhost:8080
// @BasePath        /
// @securityDefinitions.apikey  BearerAuth
// @in                          header
// @name                        Authorization
// @description                 Type "Bearer" followed by a space and the JWT access token.
package main

import (
	"context"
	"errors"
	"log"
	"log/slog"
	"net/http"
	"os"
	"os/signal"
	"syscall"
	"time"

	"sportloga/internal/auth"
	authhandler "sportloga/internal/auth/handler"
	"sportloga/internal/auth/repository"
	"sportloga/internal/auth/service"
	"sportloga/internal/config"
	db "sportloga/internal/db/generated"
	"sportloga/internal/httpserver"
	"sportloga/internal/mailer"

	_ "sportloga/docs" // generated by `swag init`, provides the swagger.json the router serves
)

// shutdownTimeout is how long a graceful shutdown waits for in-flight
// requests to finish before forcing the process to exit anyway.
const shutdownTimeout = 10 * time.Second

func main() {
	// Structured logging: every log line from here on is a JSON
	// object (level, message, and whatever key/value fields a call
	// site adds), not a free-text string. This is what makes
	// production logs queryable/filterable instead of grep-only.
	slog.SetDefault(slog.New(slog.NewJSONHandler(os.Stdout, nil)))

	cfg, err := config.Load()
	if err != nil {
		log.Fatalf("config error: %v", err)
	}

	pool := mustConnectDB(cfg.DatabaseURL)
	defer pool.Close()

	queries := db.New(pool)

	jwtIssuer := auth.NewJWTIssuer(cfg.JWTSecret)
	resendMailer := mailer.NewResendMailer(cfg.ResendAPIKey, cfg.ResendFromAddress)

	authRepo := repository.NewAuthRepository(queries)
	authSvc := service.NewAuthService(authRepo, jwtIssuer, resendMailer, cfg.GoogleClientID)
	authH := authhandler.NewAuthHandler(authSvc)

	// As each new domain (realtime, notifications, betting...) gets its
	// own repo/service/handler, wire it here and add it to Handlers below.
	// Route mounting itself never happens in this file — see
	// internal/httpserver/router.go.
	handlers := httpserver.Handlers{
		Auth: authH,
	}

	r := httpserver.NewRouter(handlers, jwtIssuer, cfg.AllowedOrigins, cfg.TrustedProxyCIDRs)

	srv := &http.Server{
		Addr:    ":" + cfg.Port,
		Handler: r,
	}

	// Run the server in a goroutine so main() stays free to listen for
	// a shutdown signal below. ListenAndServe blocks until the server
	// stops; ErrServerClosed is the expected error on a clean
	// Shutdown() call, not a real failure.
	go func() {
		slog.Info("server starting", "port", cfg.Port)
		if err := srv.ListenAndServe(); err != nil && !errors.Is(err, http.ErrServerClosed) {
			log.Fatalf("server error: %v", err)
		}
	}()

	// Block until the OS asks us to stop — Ctrl+C locally (SIGINT), or
	// SIGTERM from whatever's managing the process in staging/prod
	// (systemd, Docker, a platform's deploy tooling). Without this,
	// the old log.Fatal(ListenAndServe(...)) approach meant every
	// deploy/restart just killed in-flight requests instantly.
	quit := make(chan os.Signal, 1)
	signal.Notify(quit, os.Interrupt, syscall.SIGTERM)
	<-quit

	slog.Info("shutdown signal received, draining in-flight requests")

	ctx, cancel := context.WithTimeout(context.Background(), shutdownTimeout)
	defer cancel()

	if err := srv.Shutdown(ctx); err != nil {
		log.Fatalf("forced shutdown after %s: %v", shutdownTimeout, err)
	}

	slog.Info("server exited cleanly")
}
